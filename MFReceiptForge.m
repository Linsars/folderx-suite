static NSMutableData *mfRcInAppSet(void) {
    NSMutableArray<NSData *> *items = [NSMutableArray array];
    NSString *now = mfRcNowISO();
    long long nowMs = (long long)([[NSDate date] timeIntervalSince1970] * 1000);
    NSString *far = @"2099-09-09T09:09:09Z";
    long long farMs = 4097702400000LL; // 2099-09-09
    long long i = 0;
    for (NSString *pid in mfSubPids()) {
        NSMutableData *inner = [NSMutableData data];
        [inner appendData:mfDerAttr(1701, mfDerInt(1))];                    // quantity
        [inner appendData:mfDerAttr(1702, mfDerUtf8(pid))];                 // product_id
        [inner appendData:mfDerAttr(1703, mfDerUtf8([NSString stringWithFormat:@"mfsk1.rc.%lld", i]))];
        [inner appendData:mfDerAttr(1704, mfDerUtf8(now))];                 // purchase_date
        [inner appendData:mfDerAttr(1705, mfDerUtf8([NSString stringWithFormat:@"mfsk1.rc.%lld", i]))];
        [inner appendData:mfDerAttr(1706, mfDerUtf8(now))];                 // original_purchase_date
        [inner appendData:mfDerAttr(1708, mfDerUtf8(far))];                 // expires_date
        [inner appendData:mfDerAttr(1711, mfDerUtf8([NSString stringWithFormat:@"%lld", i + 1]))];
