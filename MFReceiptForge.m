// PKCS7 payload: 主收据属性 SET
static NSMutableData *mfRcPayload(void) {
    NSString *bundleID = [NSBundle mainBundle].bundleIdentifier ?: @"com.mf.unknown";
    NSString *ver = [[NSBundle mainBundle] objectForInfoDictionaryKey:@"CFBundleShortVersionString"] ?: @"1.0";

    uint8_t opaque[16];
    arc4random_buf(opaque, sizeof(opaque));
    NSMutableData *opaqueD = [NSMutableData dataWithBytes:opaque length:16];

    // SHA1(opaque + bundle_id + guid?) — guid 未知, 补零(SwiftyStoreKit 严格 hash 校验会挂, 解析型无影响)
    NSMutableData *hashIn = [NSMutableData dataWithData:opaqueD];
    [hashIn appendData:[bundleID dataUsingEncoding:NSUTF8StringEncoding]];
    uint8_t zeros[16] = {0}; [hashIn appendBytes:zeros length:16];
    uint8_t sha[CC_SHA1_DIGEST_LENGTH];
    CC_SHA1(hashIn.bytes, (int)hashIn.length, sha);
    NSMutableData *shaD = [NSMutableData dataWithBytes:sha length:CC_SHA1_DIGEST_LENGTH];

    NSMutableArray<NSData *> *attrs = [NSMutableArray array];
    [attrs addObject:mfDerAttr(0, mfDerSeq(@[]))];                       // padding
    [attrs addObject:mfDerAttr(2, mfDerUtf8(bundleID))];
    [attrs addObject:mfDerAttr(3, mfDerUtf8(ver))];
    [attrs addObject:mfDerAttr(4, opaqueD)];
    [attrs addObject:mfDerAttr(5, shaD)];
    [attrs addObject:mfDerAttr(12, mfDerUtf8(mfRcNowISO()))];
    [attrs addObject:mfDerAttr(19, mfDerUtf8(ver))];                     // original_application_version
    [attrs addObject:mfDerSet(@[mfDerInt(17), mfRcInAppSet()])];         // in_app
    NSMutableData *payload = mfDerSet(attrs);
    return mfDerOctet(payload); // eContent = OCTET STRING
}

// PKCS7 SignedData 信封
static NSMutableData *mfRcContainer(void) {
    NSMutableData *cert = [NSMutableData dataWithBytes:g_mfFakeCert length:g_mfFakeCertLen];

    NSMutableData *sig = [NSMutableData data];
    uint8_t sigb[128] = {0}; [sig appendBytes:sigb length:128];

    NSMutableData *signer = mfDerSeq(@[
        mfDerInt(1),
        mfDerSeq(@[ mfDerSeq(@[ mfDerTlv(0x06, [NSData dataWithBytes:(uint8_t[]){0x55,0x04,0x03} length:3]),
                                   mfDerUtf8(@"MF Receipt Signer") ]),
                    mfDerOctet([NSData dataWithBytes:(uint8_t[]){0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08} length:8]) ]),
        mfDerTlv(0x06, [NSData dataWithBytes:(uint8_t[]){0x2B,0x0E,0x03,0x02,0x1A} length:5]),           // sha1
        mfDerTlv(0x06, [NSData dataWithBytes:(uint8_t[]){0x2A,0x86,0x48,0x86,0xF7,0x0D,0x01,0x01,0x01} length:9]), // rsa
        mfDerOctet(sig) ]);

    NSMutableData *sd = mfDerSeq(@[
        mfDerInt(1),
        mfDerSet(@[ mfDerSeq(@[ mfDerTlv(0x06, [NSData dataWithBytes:(uint8_t[]){0x2B,0x0E,0x03,0x02,0x1A} length:5]) ]) ]),
        mfDerSeq(@[ mfDerTlv(0x06, [NSData dataWithBytes:(uint8_t[]){0x2A,0x86,0x48,0x86,0xF7,0x0D,0x01,0x07,0x01} length:9]),
                     mfDerCtx(0, mfRcPayload()) ]),
        mfDerCtx(0, mfDerTlv(0x30, cert)),   // certificates [0] IMPLICIT
        mfDerTlv(0x31, mfDerSet(@[signer])) ]);

    NSMutableData *ci = mfDerSeq(@[
        mfDerTlv(0x06, [NSData dataWithBytes:(uint8_t[]){0x2A,0x86,0x48,0x86,0xF7,0x0D,0x01,0x07,0x02} length:9]),
        mfDerCtx(0, sd) ]);
    return ci;
}

#pragma mark - Hook

static NSURL *hook_receiptURL(id self, SEL _cmd) {
    if (!g_forgeOn) {
        if (orig_receiptURL) return ((NSURL *(*)(id, SEL))orig_receiptURL)(self, _cmd);
        return nil;
    }
    g_forgeHits++;
    // v2.11.4: 列表还是空(fallback only) → 透传真收据, 不喂垃圾弹夹
    NSArray *cur = mfSubPids();
    if (cur.count == 1 && [cur[0] isEqualToString:@"com.mf.premium.lifetime"]) {
        mfLog(@"[rcforge] passthrough (list empty, 先开一次 app 内购页)");
        if (orig_receiptURL) return ((NSURL *(*)(id, SEL))orig_receiptURL)(self, _cmd);
        return nil;
    }
    @try {
        NSUInteger pc = mfSubPids().count;
        static dispatch_once_t once; static dispatch_semaphore_t sem = NULL;
        dispatch_once(&once, ^{ sem = dispatch_semaphore_create(1); });
        dispatch_semaphore_wait(sem, DISPATCH_TIME_FOREVER);
        // v2.11.1: 扫描列表从空到有(或条数变化) → 强制重建收据
        BOOL stale = (!g_forgeURL || g_forgePidCount != pc);
        if (stale) {
            NSMutableData *d = mfRcContainer();
            NSString *dir = [NSSearchPathForDirectoriesInDomains(NSCachesDirectory, NSUserDomainMask, YES) firstObject];
            if (![[NSFileManager defaultManager] fileExistsAtPath:dir])
                [[NSFileManager defaultManager] createDirectoryAtPath:dir withIntermediateDirectories:YES attributes:nil error:NULL];
            NSString *path = [dir stringByAppendingPathComponent:@"mfreceipt.pkcs7"];
            [d writeToFile:path atomically:YES];
            g_forgeURL = [NSURL fileURLWithPath:path];
            g_forgePidCount = pc;
            mfLog(@"[rcforge] receipt %lu bytes pids=%lu -> %@", (unsigned long)d.length, (unsigned long)pc, path);
        }
        dispatch_semaphore_signal(sem);
        return g_forgeURL;
    } @catch (NSException *e) {
        mfLog(@"[rcforge] build fail: %@", e.name);
        if (orig_receiptURL) return ((NSURL *(*)(id, SEL))orig_receiptURL)(self, _cmd);
        return nil;
    }
}

// 旧式 transactionReceipt (SwiftyStoreKit 旧版/老 app 用) — JSON 形状
static NSData *hook_txReceipt(id self, SEL _cmd) {
    if (!g_forgeOn) {
        if (orig_txReceipt) return ((NSData *(*)(id, SEL))orig_txReceipt)(self, _cmd);
        return nil;
    }
    g_forgeHits++;
    NSString *pid = @"com.mf.product";
    id pay = objc_getAssociatedObject(self, "mfsk1_pay");
    if (pay) pid = objc_getAssociatedObject(pay, "mfsk1_pid") ?: pid;
    NSString *now = mfRcNowISO();
    long long nowMs = (long long)([[NSDate date] timeIntervalSince1970] * 1000);
    long long tid = 100000 + arc4random() % 900000;
    NSMutableData *sigD = [NSMutableData dataWithBytes:g_mfOldSig length:g_mfOldSigLen];
    NSString *json = [NSString stringWithFormat:
        @"{\"signature\":\"%@\",\"pod\":\"44\",\"signing-status\":\"0\",\"purchase-info\":"
        @"{\"quantity\":\"1\",\"product_id\":\"%@\",\"transaction_id\":\"%lld\","
        @"\"original_transaction_id\":\"%lld\",\"purchase_date\":\"%@\",\"purchase_date_ms\":\"%lld\","
        @"\"original_purchase_date\":\"%@\",\"original_purchase_date_ms\":\"%lld\","
        @"\"expires_date\":\"2099-09-09T09:09:09Z\",\"unique_identifier\":\"mfsk1-uid\","
        @"\"unique_vendor_identifier\":\"mfsk1-vuid\"}}",
        [sigD base64EncodedStringWithOptions:0], pid, tid, tid, now, nowMs, now, nowMs];
    return [json dataUsingEncoding:NSUTF8StringEncoding];
}

#pragma mark - 开关/持久化

void mfReceiptForgeEnable(void) {
    if (g_forgeOn) return;
    g_forgeURL = nil; // 重开时强制重新生成
    Class b = [NSBundle class];
    Method m1 = class_getInstanceMethod(b, @selector(appStoreReceiptURL));
    if (m1) orig_receiptURL = method_setImplementation(m1, (IMP)hook_receiptURL);
    Method m2 = class_getInstanceMethod(objc_getClass("SKPaymentTransaction"), @selector(transactionReceipt));
    if (m2) orig_txReceipt = method_setImplementation(m2, (IMP)hook_txReceipt);
    g_forgeOn = YES;
    mfLog(@"[rcforge] ON (url:%d txreceipt:%d)", m1 != NULL, m2 != NULL);
}

void mfReceiptForgeDisable(void) {
    if (!g_forgeOn) return;
    Class b = [NSBundle class];
    Method m1 = class_getInstanceMethod(b, @selector(appStoreReceiptURL));
    if (m1 && orig_receiptURL) method_setImplementation(m1, orig_receiptURL);
    Method m2 = class_getInstanceMethod(objc_getClass("SKPaymentTransaction"), @selector(transactionReceipt));
    if (m2 && orig_txReceipt) method_setImplementation(m2, orig_txReceipt);
    orig_receiptURL = orig_txReceipt = NULL;
    g_forgeURL = nil;
    g_forgeOn = NO;
    mfLog(@"[rcforge] OFF");
}

void mfReceiptForgeInvalidate(void) {
    g_forgeURL = nil;
    g_forgePidCount = NSUIntegerMax;
}

void mfReceiptForgeSwitchChanged(UISwitch *sw) {
    if (sw.on) { mfReceiptForgeEnable(); mfToast(@"🧾 收据伪造已开启"); }
    else { mfReceiptForgeDisable(); mfToast(@"⏹️ 收据伪造已关闭"); }
    [[NSUserDefaults standardUserDefaults] setBool:sw.on forKey:@"mfReceiptForgeEnabled"];
    [[NSUserDefaults standardUserDefaults] synchronize];
    if (sw.on) g_forgeURL = nil, g_forgePidCount = NSUIntegerMax; // 开关即重建
}

void mfReceiptForgeAutoStart(void) {
    if (![[NSUserDefaults standardUserDefaults] boolForKey:@"mfReceiptForgeEnabled"]) return;
    mfReceiptForgeEnable();
}

long mfReceiptForgeHits(void) { return g_forgeHits; }
BOOL mfReceiptForgeIsOn(void) { return g_forgeOn; }
