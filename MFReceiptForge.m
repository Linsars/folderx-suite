static NSMutableData *mfDerLen(NSUInteger n) {
    NSMutableData *d = [NSMutableData data];
    if (n < 0x80) { uint8_t b = (uint8_t)n; [d appendBytes:&b length:1]; }
    else {
        uint8_t tmp[8]; int i = 0;
        while (n) { tmp[i++] = n & 0xFF; n >>= 8; }
        uint8_t first = (uint8_t)(0x80 | i); [d appendBytes:&first length:1];
        while (i--) [d appendBytes:&tmp[i] length:1];
    }
    return d;
}
static NSMutableData *mfDerTlv(uint8_t tag, NSData *content) {
    NSMutableData *d = [NSMutableData dataWithBytes:&tag length:1];
    [d appendData:mfDerLen(content.length)];
    [d appendData:content];
    return d;
}
static NSMutableData *mfDerJoin(NSArray<NSData *> *parts) {
    NSMutableData *d = [NSMutableData data];
    for (NSData *p in parts) [d appendData:p];
    return d;
}
static NSMutableData *mfDerSeq(NSArray<NSData *> *parts) { return mfDerTlv(0x30, mfDerJoin(parts)); }
static NSMutableData *mfDerSet(NSArray<NSData *> *parts) { return mfDerTlv(0x31, mfDerJoin(parts)); }
static NSMutableData *mfDerInt(long long v) {
    NSMutableData *body = [NSMutableData data];
    uint8_t buf[8]; int n = 0;
    unsigned long long u = v < 0 ? -v : v;
    int neg = v < 0;
    do { buf[n++] = u & 0xFF; u >>= 8; } while (u);
    if (neg) { buf[0] = -buf[0]; }
    uint8_t first = buf[n-1] & 0x80 ? 0x00 : buf[n-1];
    if (!neg && (buf[n-1] & 0x80)) { uint8_t z = 0; [body appendBytes:&z length:1]; }
    for (int i = n - 1; i >= 0; i--) [body appendBytes:&buf[i] length:1];
    (void)first;
    return mfDerTlv(0x02, body);
}
static NSMutableData *mfDerUtf8(NSString *s) {
    return mfDerTlv(0x0C, [s dataUsingEncoding:NSUTF8StringEncoding] ?: [NSData data]);
}
static NSMutableData *mfDerOctet(NSData *d) { return mfDerTlv(0x04, d); }
static NSMutableData *mfDerCtx(uint8_t n, NSData *content) { return mfDerTlv(0xA0 + n, content); }
static NSMutableData *mfDerAttr(long long type, NSData *value) {
    return mfDerSet(@[mfDerInt(type), value]);
}

